//! Mirrors, pacman and the AUR.

use crate::step::Step;
use crate::system::Cmd;
use crate::tweak::{Availability, Group, OptionValue, Tweak, TweakOption};

/// Always fits: every Arch machine has pacman.
fn always(_: &mut dyn crate::system::System) -> Availability {
    Availability::Yes
}

/// The mirror list, refreshed by reflector and kept fresh by its timer.
///
/// The country and the count go into reflector's own configuration file, which is the one
/// `reflector.timer` reads every week, and the first list is made from that same file: a
/// timer that rewrote the list from a file without them would, a week later, swap the
/// country the person chose for mirrors from anywhere. The package ships a default of that
/// file, so it is replaced rather than owned, and its backup brings the default back.
///
/// The list's check greps for reflector's own header rather than testing that the file merely
/// exists: every stock Arch install already has a non-empty `mirrorlist`, so `test -s` would
/// report this tweak as permanently applied and never run. The list's undo comes from
/// `Step::FileRewritten`, which captures its prior content itself. The timer writes the list
/// again every week, so what qtools wrote is no tripwire for it: the undo puts back the list
/// from before qtools, whatever the timer wrote since.
pub fn mirrors(country: &str, count: u32) -> Tweak {
    Tweak {
        id: "mirrors",
        group: Group::Packages,
        options: vec![
            TweakOption { key: "mirrors.country", value: OptionValue::Text(country.to_owned()) },
            TweakOption { key: "mirrors.count", value: OptionValue::Count(count) },
        ],
        steps: vec![
            Step::PackageInstalled { package: "reflector" },
            Step::FileReplaced { path: REFLECTOR_CONF, content: reflector_conf(country, count) },
            Step::FileRewritten {
                path: MIRRORLIST,
                run: Cmd::new("reflector", [format!("@{REFLECTOR_CONF}")]).root(),
                check: Cmd::new("sh", ["-c", "grep -q 'generated by Reflector' /etc/pacman.d/mirrorlist"]),
                label: "reflector",
                renewed: true,
            },
            Step::ServiceEnabled { unit: "reflector.timer" },
        ],
        applies_to: always,
    }
}

/// The file `reflector.timer` runs reflector with, one argument a line.
const REFLECTOR_CONF: &str = "/etc/xdg/reflector/reflector.conf";

/// reflector's configuration for the mirrors of `country`, the `count` fastest of them.
///
/// reflector splits each line of the file the way a shell would, so a country name with a space
/// in it is quoted to stay one argument. The country holds only letters, spaces, commas and
/// hyphens (see `crate::choices::country_ok`), so single quotes carry it as it is.
fn reflector_conf(country: &str, count: u32) -> String {
    let country = if country.contains(' ') { format!("'{country}'") } else { country.to_owned() };
    format!(
        "# Written by qtools: the mirrors reflector.timer keeps fresh.\n\
         --save {MIRRORLIST}\n--protocol https\n--country {country}\n--latest {count}\n--sort rate\n"
    )
}

const MIRRORLIST: &str = "/etc/pacman.d/mirrorlist";

/// The pacman options the community recommends.
///
/// `Color` and `VerbosePkgLists` are valueless pacman directives — the line is just the
/// key, with no `=` — so they carry an empty `value`; `ConfOption` and `conf::set_option`
/// treat an empty value as a bare directive rather than `key = `.
pub fn pacman_options(parallel: u32) -> Tweak {
    Tweak {
        id: "pacman-options",
        group: Group::Packages,
        options: vec![TweakOption { key: "pacman.parallel", value: OptionValue::Count(parallel) }],
        steps: vec![
            Step::ConfOption {
                file: PACMAN_CONF,
                section: Some("options"),
                key: "ParallelDownloads",
                value: parallel.to_string(),
            },
            Step::ConfOption { file: PACMAN_CONF, section: Some("options"), key: "Color", value: String::new() },
            Step::ConfOption {
                file: PACMAN_CONF,
                section: Some("options"),
                key: "VerbosePkgLists",
                value: String::new(),
            },
        ],
        applies_to: always,
    }
}

/// The 32-bit repository, needed by Steam and by some drivers.
///
/// This one is a section rather than an option, so `ConfOption` cannot express it: the
/// check asks pacman itself whether the repository is there. The undo comes from the
/// file's own captured content, via `Step::FileRewritten`, rather than from a `sed`
/// command trying to cut the section back out — that could never restore what it never
/// recorded, and risked leaving a stray blank line behind.
pub fn multilib() -> Tweak {
    Tweak {
        id: "multilib",
        group: Group::Packages,
        options: Vec::new(),
        steps: vec![Step::FileRewritten {
            path: PACMAN_CONF,
            run: Cmd::new(
                "sh",
                ["-c", "printf '\\n[multilib]\\nInclude = /etc/pacman.d/mirrorlist\\n' >> /etc/pacman.conf"],
            )
            .root(),
            check: Cmd::new("sh", ["-c", "pacman-conf --repo-list | grep -qx multilib"]),
            label: "multilib",
            renewed: false,
        }],
        applies_to: always,
    }
}

/// An AUR helper, built from the AUR itself.
pub fn aur_helper(helper: &'static str) -> Tweak {
    Tweak {
        id: "aur-helper",
        group: Group::Packages,
        options: vec![TweakOption {
            key: "aur.helper",
            value: OptionValue::Choice { chosen: usize::from(helper == "yay"), options: vec!["aur.paru", "aur.yay"] },
        }],
        steps: vec![
            // The build tools stay when the helper is undone: by then they may build other things.
            Step::PackageNeeded { package: "base-devel" },
            Step::PackageNeeded { package: "git" },
            Step::CommandRun {
                run: Cmd::new("sh", ["-c", &build_script(helper)]),
                // `command` is a shell builtin, not a binary `RealSystem::run` could exec
                // directly, so the check runs it through a shell, the same way the
                // `multilib` check does.
                check: Cmd::new("sh", ["-c", &format!("command -v {helper}")]),
                undo: Cmd::new("pacman", ["-Rns", "--noconfirm", helper]).root(),
                label: helper,
            },
        ],
        applies_to: always,
    }
}

/// Keeps the package cache from growing without end.
pub fn cache_cleanup() -> Tweak {
    Tweak {
        id: "cache-cleanup",
        group: Group::Packages,
        options: Vec::new(),
        steps: vec![
            Step::PackageInstalled { package: "pacman-contrib" },
            Step::ServiceEnabled { unit: "paccache.timer" },
        ],
        applies_to: always,
    }
}

const PACMAN_CONF: &str = "/etc/pacman.conf";

/// Cloning the helper's package and building it, in one shell line, in a temporary folder
/// that is taken away when the line ends, whether the build went through or not.
///
/// `helper` is interpolated into this shell command unescaped, so it must stay a
/// trusted literal — one of the catalog's own `"paru"`/`"yay"` — never text a person typed.
fn build_script(helper: &str) -> String {
    format!(
        "dir=\"$(mktemp -d)\" && trap 'rm -rf \"$dir\"' EXIT && cd \"$dir\" && git clone https://aur.archlinux.org/{helper}.git && cd {helper} && makepkg -si --noconfirm"
    )
}
