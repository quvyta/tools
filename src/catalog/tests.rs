/// The opening of Arch's own `/etc/pacman.conf`, trimmed, with the three options commented
/// out or missing, and the repositories after `[options]`, a person's own one last.
const STOCK_PACMAN_CONF: &str = "\
[options]
HoldPkg     = pacman glibc
Architecture = auto
#Color
CheckSpace
SigLevel    = Required DatabaseOptional
LocalFileSigLevel = Optional

# REPOSITORIES

[core]
Include = /etc/pacman.d/mirrorlist

[extra]
Include = /etc/pacman.d/mirrorlist

[mine]
Server = file:///home/me/repo
";

// pacman reads an option in the section it is in: `ParallelDownloads` and `VerbosePkgLists`,
// which the stock file does not carry at all, used to be added at the end of the file, under
// the person's own repository, where pacman takes them for that repository's directives.
#[test]
fn pacman_options_go_into_the_options_section_of_a_real_pacman_conf() {
    let mut system = FakeSystem::new();
    system.file("/etc/pacman.conf", STOCK_PACMAN_CONF);
    let mut journal = crate::state::Journal::default();

    packages::pacman_options(5).apply(&mut system, &mut journal, std::path::Path::new("/tmp/state")).expect("it runs");

    let written = system.read(std::path::Path::new("/etc/pacman.conf")).unwrap().expect("the file is there");
    let options = written.split("[core]").next().expect("the options come first");
    for line in ["ParallelDownloads = 5", "Color", "VerbosePkgLists"] {
        assert!(options.lines().any(|found| found == line), "`{line}` is not under [options]:\n{written}");
    }
    let repositories = written.split("[core]").nth(1).expect("the repositories follow");
    assert!(
        !repositories.contains("ParallelDownloads") && !repositories.contains("VerbosePkgLists"),
        "nothing lands under a repository:\n{written}"
    );
}

