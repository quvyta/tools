#[test]
fn applying_the_firewall_runs_every_step_as_root_and_checks_without_root() {
    let mut system = FakeSystem::new();
    system.answer("pacman -Q ufw", no());
    system.answer(UFW_CHECK, no());
    system.answer("systemctl is-enabled ufw.service", no());
    system.answer("systemctl is-active ufw.service", no());
    system.answer("sudo pacman -S --needed --noconfirm ufw", ok(""));
    system.answer("sudo ufw --force enable", ok("Firewall is active and enabled on system startup"));
    system.answer("sudo systemctl enable --now ufw.service", ok(""));
    let mut journal = crate::state::Journal::default();

    security::firewall().apply(&mut system, &mut journal, std::path::Path::new("/tmp/state")).expect("it runs");

    let root_calls: Vec<&String> = system.calls().iter().filter(|call| call.starts_with("sudo ")).collect();
    assert_eq!(
        root_calls,
        [
            "sudo pacman -S --needed --noconfirm ufw",
            "sudo ufw --force enable",
            "sudo systemctl enable --now ufw.service"
        ]
    );
    assert!(system.calls().contains(&UFW_CHECK.to_owned()), "{:?}", system.calls());
}

