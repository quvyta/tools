const REFLECTOR_CONF: &str = "/etc/xdg/reflector/reflector.conf";

/// A machine with reflector installed, its package's own configuration and a stock mirror list.
fn with_reflector() -> FakeSystem {
    let mut system = FakeSystem::new();
    system.answer("pacman -Q reflector", ok("reflector 2023-1"));
    system.file(REFLECTOR_CONF, "--save /etc/pacman.d/mirrorlist\n--protocol https\n--latest 5\n--sort age\n");
    system.file("/etc/pacman.d/mirrorlist", "Server = https://geo.mirror.pkgbuild.com/$repo/os/$arch\n");
    system.answer("sh -c grep -q 'generated by Reflector' /etc/pacman.d/mirrorlist", no());
    system.answer("systemctl is-enabled reflector.timer", no());
    system.answer("systemctl is-active reflector.timer", no());
    system.answer(&format!("sudo reflector @{REFLECTOR_CONF}"), ok(""));
    system.answer("sudo systemctl enable --now reflector.timer", ok(""));
    system
}

// `reflector.timer` runs reflector with its own configuration file. The country and count used
// to reach only the first run, and a week later the timer rewrote the list with mirrors from
// anywhere; they are in the file the timer reads now, and the first list is made from it.
#[test]
fn the_chosen_country_and_count_reach_the_file_the_timer_reads() {
    let mut system = with_reflector();
    let mut journal = crate::state::Journal::default();

    packages::mirrors("DE", 20).apply(&mut system, &mut journal, std::path::Path::new("/tmp/state")).expect("it runs");

    let conf = system.read(std::path::Path::new(REFLECTOR_CONF)).unwrap().expect("the configuration is written");
    assert!(conf.lines().any(|line| line == "--country DE"), "{conf}");
    assert!(conf.lines().any(|line| line == "--latest 20"), "{conf}");
    assert!(conf.lines().any(|line| line == "--save /etc/pacman.d/mirrorlist"), "{conf}");
    assert!(
        system.calls().iter().any(|call| call == &format!("sudo reflector @{REFLECTOR_CONF}")),
        "the first list is made from the same file: {:?}",
        system.calls()
    );
}

// The timer writes the list again every week, so what qtools wrote is no tripwire for it: the
// undo still puts back the list and the configuration from before qtools.
#[test]
fn undoing_the_mirrors_puts_back_the_list_the_timer_has_rewritten_since() {
    let mut system = with_reflector();
    let mut journal = crate::state::Journal::default();
    let folder = std::path::Path::new("/tmp/state");
    let tweak = packages::mirrors("DE", 20);
    tweak.apply(&mut system, &mut journal, folder).expect("it runs");

    system.file("/etc/pacman.d/mirrorlist", "# generated by Reflector a week later\nServer = https://x/\n");
    system.answer("sudo systemctl disable --now reflector.timer", ok(""));
    tweak.revert(&mut system, &mut journal, folder).expect("the timer's list is no reason to refuse");

    assert_eq!(
        system.read(std::path::Path::new("/etc/pacman.d/mirrorlist")).unwrap().as_deref(),
        Some("Server = https://geo.mirror.pkgbuild.com/$repo/os/$arch\n")
    );
    assert_eq!(
        system.read(std::path::Path::new(REFLECTOR_CONF)).unwrap().as_deref(),
        Some("--save /etc/pacman.d/mirrorlist\n--protocol https\n--latest 5\n--sort age\n"),
        "the package's own configuration is back"
    );
}

// reflector reads its configuration a line at a time and splits each line the way a shell would,
// so a country name with a space, which the option form allows, would reach reflector as two
// arguments and stop the timer's every run.
#[test]
fn a_country_name_with_a_space_reaches_reflector_as_one_argument() {
    let tweak = packages::mirrors("United States", 10);
    let Some(crate::step::Step::FileReplaced { content, .. }) = tweak.steps.get(1) else {
        panic!("the second step writes reflector's configuration")
    };
    assert!(content.lines().any(|line| line == "--country 'United States'"), "{content}");
    let plain = packages::mirrors("DE,FR", 10);
    let Some(crate::step::Step::FileReplaced { content, .. }) = plain.steps.get(1) else { panic!() };
    assert!(content.lines().any(|line| line == "--country DE,FR"), "{content}");
}

