    system.answer(NVIDIA_INITRAMFS_IS_CURRENT, no());
    for unit in ["nvidia-suspend.service", "nvidia-resume.service", "nvidia-hibernate.service"] {
        system.answer(&format!("sudo systemctl enable {unit}"), ok(""));
    }
    system.answer("sudo mkinitcpio -P", ok(""));
    let mut journal = crate::state::Journal::default();

    hardware::nvidia_wayland().apply(&mut system, &mut journal, std::path::Path::new("/tmp/state")).expect("it runs");

