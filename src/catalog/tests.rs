#[test]
fn every_tweak_and_group_reads_fully_in_both_languages() {
    let env = crate::locales::env();
    assert_eq!(env.diagnostics(), &[]);
    assert_eq!(env.i18n().missing_keys("tr", "en"), Vec::<String>::new());

    // Each language must carry the key itself: a borrowed English text would read on screen,
    // but `has` says `false` for it, which is what keeps the Turkish file complete.
    let reads = |key: &str| {
        for code in ["en", "tr"] {
            assert!(env.i18n().has(code, key), "`{key}` has no text in `{code}`");
        }
    };

    for group in Group::ALL {
        reads(&format!("group.{}", group.key()));
    }
    for tweak in all() {
        reads(&format!("tweak.{}.title", tweak.id));
        reads(&format!("tweak.{}.summary", tweak.id));
        for option in &tweak.options {
            reads(&format!("option.{}", option.key));
        }
    }
}

