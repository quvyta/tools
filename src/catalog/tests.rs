#[test]
fn every_command_the_microcode_item_writes_with_is_in_the_preview() {
    let mut system = machine_with(Cpu::Intel);
    let tweak = hardware::microcode(Cpu::Intel);
    // The preview is drawn from exactly this list, one line per touched thing.
    let shown = tweak.touches();
    let mut journal = crate::state::Journal::default();

    tweak.apply(&mut system, &mut journal, std::path::Path::new("/tmp/state")).expect("it runs");

    for call in system.calls() {
        let Some(run) = call.strip_prefix("sudo ") else {
            // Everything qtools runs without a password is a question it asks the machine.
            assert!(
                call.starts_with("pacman -Q ") || call.starts_with("sh -c "),
                "`{call}` changes something and the preview does not name it: {shown:?}"
            );
            continue;
        };
        // A package touch is shown by its name and a command touch by the command itself, so
        // the run that stands behind each of them is in the preview by name.
        let named = shown.iter().any(|touch| match touch {
            Touch::Package(package) => run.starts_with("pacman -S") && run.ends_with(package.as_str()),
            Touch::Command(label) => *label == run,
            _ => false,
        });
        assert!(named, "`{run}` is missing from the preview: {shown:?}");
    }
    assert!(
        shown.contains(&Touch::Command("mkinitcpio -P".into())),
        "the rebuild is a command in the preview: {shown:?}"
    );
}

