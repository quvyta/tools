// base-devel brings the compiler and make, git brings git: once they are on the machine the
// person may build other things with them. Undoing the AUR helper removes the helper, and
// leaves the tools it needed where they are.
#[test]
fn undoing_the_aur_helper_removes_the_helper_and_leaves_its_build_tools() {
    let mut system = FakeSystem::new();
    for package in ["base-devel", "git"] {
        system.answer(&format!("pacman -Q {package}"), no());
        system.answer(&format!("sudo pacman -S --needed --noconfirm {package}"), ok(""));
    }
    system.answer("sh -c command -v paru", no());
    let build = system_build_line("paru");
    system.answer(&build, ok(""));
    system.answer("sudo pacman -Rns --noconfirm paru", ok(""));
    let mut journal = crate::state::Journal::default();
    let folder = std::path::Path::new("/tmp/state");
    let tweak = packages::aur_helper("paru");
    tweak.apply(&mut system, &mut journal, folder).expect("it runs");

    tweak.revert(&mut system, &mut journal, folder).expect("it comes back");

    let removed: Vec<&String> = system.calls().iter().filter(|call| call.contains("-Rns")).collect();
    assert_eq!(removed, ["sudo pacman -Rns --noconfirm paru"]);
    assert!(!journal.has("aur-helper"), "nothing is left on record");
}

/// The line the fake machine sees for building `helper`.
fn system_build_line(helper: &str) -> String {
    let tweak = packages::aur_helper(if helper == "yay" { "yay" } else { "paru" });
    let Some(crate::step::Step::CommandRun { run, .. }) = tweak.steps.last() else { panic!("the build is a command") };
    run.argv().join(" ")
}

